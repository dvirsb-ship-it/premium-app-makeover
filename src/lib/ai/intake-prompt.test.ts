import { describe, it, expect } from "vitest";
import { INTAKE_SYSTEM_PROMPT } from "./intake-prompt";

/**
 * חוקת הקליטה מול הסקירה המשפטית (19/8/2026).
 *
 * הפרומפט הוא מסמך משפטי בפועל: הוא מה שמונע מהמנוע לחצות את סעיף 20
 * לחוק לשכת עורכי הדין. הבדיקות מנסחות את הדרישות כתנאים, כדי שעריכה
 * תמימה תיפול כאן ולא אצל עורך דין.
 *
 * לקח אמיתי: אחרי שינוי שם המסוף ל-[READY] נשארה בסוף הפרומפט הפניה
 * ל-[SUMMARY] — מסוף שהפרסר אינו מכיר. בדיקת העקביות למטה נולדה מזה.
 */

describe("חוקת הקליטה — הגבול המשפטי", () => {
  const p = INTAKE_SYSTEM_PROMPT;

  it("האיסור המרכזי קיים ומנוסח כאיסור מוחלט", () => {
    expect(p).toContain("אינך קובע, מעריך, מרמז או שוקל דבר בעל משמעות משפטית");
    expect(p).toContain("לדחות פנייה");
  });

  it("אין מסלול דחייה — ההכרעה של עורך הדין בלבד", () => {
    expect(p).not.toContain("[NOT_SUITABLE]");
    expect(p).not.toContain("שומר הסף");
  });

  it("אין סיווג לתחום — הבחירה של הפונה במסך נפרד", () => {
    expect(p).toContain("לעולם אל תסווג את המקרה לתחום");
  });

  it("המנוע אינו קורא לפעולתו בדיקה", () => {
    expect(p).not.toContain("בדיקה ראשונית");
    expect(p).not.toContain("בדיקה משפטית");
  });
});

describe("חוקת הקליטה — מסוף ועומק", () => {
  const p = INTAKE_SYSTEM_PROMPT;

  it("מסוף אחד ויחיד: [READY] — כולל בהוראת התיקון", () => {
    expect(p).toContain("[READY]");
    expect(p).not.toContain("[SUMMARY]");
  });

  it("רצפת העומק קיימת — לא מסכמים אחרי הודעה אחת", () => {
    expect(p).toContain("2-3 שאלות העמקה");
  });

  it("התאמה למי שאינו תובע — שאלות לפי עובדות המצב", () => {
    expect(p).toContain("נחקר או נאשם");
  });

  it("אין בקשת קבצים ואין בקשת מזהים", () => {
    expect(p).toContain("אל תבקש לצרף או לשלוח קבצים");
    expect(p).toContain("אל תבקש תעודת זהות");
  });
});
