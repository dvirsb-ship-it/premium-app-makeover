/**
 * ניקוי מזהים ישירים לפני שליחה למנוע ה-AI.
 *
 * הבדיקה המשפטית זקוקה ל**עובדות** — מה קרה, מתי, איזה נזק, מי אחראי.
 * היא אינה זקוקה למספר תעודת הזהות של הפונה, לטלפון שלו או למייל.
 * המספרים האלה אינם משנים אם קיימת עילה, אבל הם המפתחות שמקשרים בין
 * המקרה לאדם — ולכן הם בדיוק מה שלא צריך לצאת החוצה.
 *
 * **הניקוי הוא בדרך החוצה בלבד.** `description` שנשמר ב-Firestore ומוצג
 * ללקוח אינו נוגע בזה: הפונקציה נקראת על הטקסט שנבנה לקראת הקריאה
 * ל-Gemini, ולא על מה שנשמר. מי שיזיז אותה למעלה בשרשרת ישבור את
 * ההבטחה הזו.
 *
 * **מה שהיא לא עושה: שמות.** בעברית אי אפשר לזהות שם בטקסט חופשי בלי
 * מודל ייעודי — "נפגעתי ברחוב הרצל" היה נהרס. שם לבדו גם הרבה פחות
 * מקשר מאשר מספר זהות. מוטב להסיר שלושה דברים באמת מאשר להבטיח הכל
 * ולקיים חלקית, במיוחד כשההבטחה הזו נכנסת למדיניות הפרטיות.
 */

export const REDACTED_ID = "[מספר זהות הוסר]";
export const REDACTED_PHONE = "[טלפון הוסר]";
export const REDACTED_EMAIL = "[דוא״ל הוסר]";

/**
 * הניקוי **דלוק** — 6/8/2026.
 *
 * עלה כבוי בבוקר, כי בדיקות יכולות לאמת שהפונקציה מנקה נכון — לא
 * שהתזכיר עדיין יוצא באיכות זהה. זה מתאמת רק בתיק אמיתי מול Gemini.
 *
 * הודלק כדי שדביר יפתח תיק בדיקה **עם** הניקוי פעיל ונראה את התוצאה.
 * אם התזכיר יוצא רדוד או שהשופט הפנימי פוסל בלי סיבה — חזרה ל-false,
 * תו אחד, בלי לגעת בשתי נקודות היציאה.
 */
export const AI_REDACTION_ENABLED = true;

/**
 * ספרת הביקורת של תעודת זהות ישראלית.
 *
 * בלעדיה כל רצף של תשע ספרות היה נמחק — מספר חשבונית, מספר תיק, סכום.
 * הבדיקה הזו היא ההפרש בין ניקוי מדויק לבין השחתת הטקסט שהבדיקה
 * המשפטית מסתמכת עליו.
 */
export function isIsraeliId(digits: string): boolean {
  if (!/^\d{5,9}$/.test(digits)) return false;
  const id = digits.padStart(9, "0");
  let sum = 0;
  for (let i = 0; i < 9; i++) {
    let n = Number(id[i]) * ((i % 2) + 1);
    if (n > 9) n -= 9;
    sum += n;
  }
  return sum % 10 === 0;
}

/*
 * הסדר כאן אינו שרירותי:
 *
 * 1. מייל ראשון — הוא עלול להכיל ספרות שייראו כמו טלפון.
 * 2. טלפון לפני תעודת זהות — מספר בן עשר ספרות מכיל בתוכו רצף של תשע,
 *    וללא הסדר הזה מנקה-הזהות היה קורע חצי מספר טלפון ומשאיר ספרה
 *    יתומה בטקסט.
 */
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

/** נייד וקווי ישראלי, עם או בלי מקף/רווח, ועם קידומת בינלאומית */
const PHONE = /(?:\+?972[-\s]?|\b0)(?:5\d|7\d|[23489])[-\s]?\d{3}[-\s]?\d{4}\b/g;

/** רצף ספרות עצמאי שעשוי להיות תעודת זהות */
const MAYBE_ID = /\b\d{5,9}\b/g;

/**
 * הניקוי עצמו — טהור ותמיד פעיל, ועליו נשענות הבדיקות.
 * מחזיר את הטקסט כמות שהוא כשאין מה להסיר.
 */
export function redactIdentifiers(text: string): string {
  if (!text) return text;
  return text
    .replace(EMAIL, REDACTED_EMAIL)
    .replace(PHONE, REDACTED_PHONE)
    .replace(MAYBE_ID, (m) => (isIsraeliId(m) ? REDACTED_ID : m));
}

/**
 * מה שנקרא בפועל לפני שליחה ל-AI — כפוף למתג.
 *
 * ההפרדה מכוונת: הבדיקות בודקות את `redactIdentifiers` ולכן נשארות
 * משמעותיות גם כשהמתג כבוי, ואין צורך לגעת בשתי נקודות היציאה
 * ב-intake.functions כדי להדליק או לכבות.
 */
export function redactForAi(text: string): string {
  return AI_REDACTION_ENABLED ? redactIdentifiers(text) : text;
}
